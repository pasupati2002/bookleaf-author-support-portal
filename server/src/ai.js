const OLLAMA_URL = process.env.OLLAMA_URL || 'http://127.0.0.1:11434';
const MODEL = process.env.AI_MODEL || 'llama3.2:3b';
const KNOWLEDGE_BASE = `
BookLeaf Publishing Knowledge Base

Company Overview:
BookLeaf Publishing supports authors with publishing, printing, distribution,
royalty, metadata, and production-related services.

Royalty Policy:
Royalty-related questions should be answered using the author's available
book and royalty information. Do not invent payment dates or amounts.
If a payment detail is unavailable, state that the support team needs to verify it.

ISBN & Metadata:
ISBN and book metadata issues should be handled carefully. Do not invent ISBNs,
metadata values, or registration details. Ask the support team to verify missing
or incorrect information.

Printing & Quality:
Printing and quality concerns should be acknowledged professionally.
Do not promise a specific resolution or replacement unless the available
information supports it.

Distribution & Availability:
Distribution questions should use the available book distribution information.
Do not claim that a book is available on a platform unless that information
is provided.

Book Status & Production Updates:
Use the provided book status and production information when available.
Do not invent production stages, dates, or completion estimates.

General Inquiry:
For questions that do not fit the categories above, provide a concise,
helpful response and state when support-team verification is required.

Tone Guidelines:
- Be professional, friendly, and concise.
- Do not invent facts, dates, payments, policies, or guarantees.
- If the Knowledge Base or ticket information does not contain an answer,
  say that the support team needs to verify it.
- Never mention that the response was generated by AI.
`;

async function askOllama(prompt) {
  const response = await fetch(`${OLLAMA_URL}/api/generate`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      model: MODEL,
      prompt,
      stream: false
    })
  });

  if (!response.ok) {
    const text = await response.text();
    throw new Error(`Ollama error ${response.status}: ${text}`);
  }

  const data = await response.json();

  return data.response.trim();
}

/**
 * Classify a support ticket.
 */
async function classifyTicket(subject, description) {
  const prompt = `
Classify this BookLeaf support ticket.

Subject: ${subject}
Description: ${description}

Return ONLY valid JSON in this exact format:
{
  "category": "one of: Royalty & Payments, ISBN & Metadata Issues, Printing & Quality, Distribution & Availability, Book Status & Production Updates, General Inquiry",
  "priority": "one of: Critical, High, Medium, Low"
}
`;

  const text = await askOllama(prompt);

  try {
    const result = JSON.parse(text);

    const validCategories = [
  'Royalty & Payments',
  'ISBN & Metadata Issues',
  'Printing & Quality',
  'Distribution & Availability',
  'Book Status & Production Updates',
  'General Inquiry'
];

    const validPriorities = [
  'Critical',
  'High',
  'Medium',
  'Low'
];

    return {
      category: validCategories.includes(result.category)
        ? result.category
        : 'General Inquiry',
      priority: validPriorities.includes(result.priority)
        ? result.priority
        : 'Medium'
    };
  } catch {
    return { category: 'General Inquiry', priority: 'Medium' };
  }
}

/**
 * Draft a reply to a support ticket.
 */
async function draftReply(ticket, book, history = []) {
  const bookInfo = book
    ? `Book: ${book.title} | status: ${book.status} | MRP: ${book.mrp ?? 'not set'} | copies sold: ${book.total_copies_sold ?? 0} | royalty earned ₹${book.total_royalty_earned ?? 0}, paid ₹${book.royalty_paid ?? 0}, pending ₹${book.royalty_pending ?? 0} | last payout: ${book.last_royalty_payout_date ?? 'none yet'} | print partner: ${book.print_partner ?? 'n/a'} | live on: ${(book.available_on || []).join(', ') || 'no platform yet'}`
    : 'No specific book (account-level query).';

  const thread = history
    .map(m => `${m.senderRole}: ${m.body}`)
    .join('\n');

  const prompt = `
You are a helpful BookLeaf Publishing support agent.

Use the following BookLeaf Knowledge Base when preparing the reply.
Do not contradict it or invent information.

${KNOWLEDGE_BASE}

Write a professional, friendly reply to the author.

Ticket subject:
${ticket.subject}

Ticket description:
${ticket.description}

${bookInfo}

Previous conversation:
${thread || 'No previous messages.'}

Rules:
- Be concise and helpful.
- Use the book/account information provided above when relevant.
- Do not invent facts, dates, payments, or policies.
- If information is missing, say that the support team will need to verify it.
- Do not mention that you are an AI.
- Return only the reply text.
`;

  return askOllama(prompt);
}

